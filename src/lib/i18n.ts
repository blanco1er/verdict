function trDate(d: string): string {
  const m = /^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d+)$/.exec(d);
  return m ? `${m[2]} ${MONTHS[m[1]]}` : d;
}

function trConcernList(x: string): string {
  return x
    .split(/ and /)
    .map((w) => FR[w.charAt(0).toUpperCase() + w.slice(1)] ?? w)
    .map((w, i) => (i === 0 ? w : w.toLowerCase()))
    .join(" et ");
}

/** French for one piece of UI text, or null when it is not UI text (a name, a number…). */
export function toFrench(text: string): string | null {
  const t = text.trim();
  if (!t || !/[A-Za-z]/.test(t)) return null;
  let out = FR[t] ?? null;
  if (out == null) {
    for (const [re, f] of PATTERNS) {
      const m = re.exec(t);
      if (m) {
        out = f(...(m as unknown as string[]));
        break;
      }
    }
  }
  if (out == null) {
    // "A, b, c." sentence of words from the dictionary (Your skin today headline)
    const parts = t.replace(/\.$/, "").split(", ");
    if (parts.length > 1 && parts.every((p) => FR[p.charAt(0).toUpperCase() + p.slice(1)])) {
      out = parts.map((p, i) => {
        const w = FR[p.charAt(0).toUpperCase() + p.slice(1)];
        return i === 0 ? w : w.toLowerCase();
      }).join(", ") + ".";
    }
  }
  if (out == null) return null;
  // keep the original surrounding spaces
  const lead = text.match(/^\s*/)?.[0] ?? "";
  const trail = text.match(/\s*$/)?.[0] ?? "";
  return lead + out + trail;
}
